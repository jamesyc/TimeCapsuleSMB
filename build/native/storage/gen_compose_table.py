#!/usr/bin/env python3
"""Write compose_table.h: the pairs shares.c composes into one character when
it names a share's smb.conf section.

Run from the repository root: python3 build/native/storage/gen_compose_table.py

The pairs are timecapsulesmb.core.smb_config.apple_composites(), the table
doctor composes with, so the device and doctor cannot disagree. Hangul
syllables are not in it; shares.c composes them arithmetically."""
import collections
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "src"))
from timecapsulesmb.core.smb_config import apple_composites  # noqa: E402

OUT = pathlib.Path(__file__).with_name("compose_table.h")


def render():
    by_mark = collections.defaultdict(list)
    for (base, mark), composite in apple_composites().items():
        # shares.c writes a composite where its two parts were.
        assert len(composite.encode()) <= len(base.encode()) + len(mark.encode())
        by_mark[ord(mark)].append((ord(base), ord(composite)))
    lines = [
        "/* Generated by gen_compose_table.py from Unicode 3.2.0; do not edit.",
        " * compose_marks: second character and index of its first pair; the",
        " * zero-mark sentinel ends the last group. compose_pairs: base, composite. */",
        "#ifndef TC_STORAGE_COMPOSE_TABLE_H",
        "#define TC_STORAGE_COMPOSE_TABLE_H",
        "static const unsigned short compose_marks[][2] = {",
    ]
    index = 0
    for mark in sorted(by_mark):
        lines.append(f"    {{0x{mark:04x}, {index}}},")
        index += len(by_mark[mark])
    lines += [f"    {{0, {index}}},", "};", "static const unsigned short compose_pairs[][2] = {"]
    for mark in sorted(by_mark):
        lines += [f"    {{0x{base:04x}, 0x{composite:04x}}}," for base, composite in sorted(by_mark[mark])]
    lines += ["};", "#endif"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render())
