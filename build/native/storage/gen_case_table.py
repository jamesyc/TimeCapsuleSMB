#!/usr/bin/env python3
"""Write case_table.h: Samba's lowercase mapping, which it applies to a share
name one code point at a time to look the share up (canonicalize_servicename,
tolower_m), so shares.c can tell which names Samba takes for one share.

Run from the repository root with the pinned Samba source (SAMBA4X_VERSION in
build/env.sh):
    python3 build/native/storage/gen_case_table.py SAMBA/lib/util/charset/codepoints.c 4.25.0

Samba's table is its own, not Unicode's: Python's str.lower() differs from it
in hundreds of code points. The header stores it as runs of code points that
move by the same amount, every code point or every other one."""
import argparse
import pathlib
import re

OUT = pathlib.Path(__file__).with_name("case_table.h")


def lowcase_table(codepoints_c):
    body = codepoints_c.split("static const uint16_t lowcase_table[] = {", 1)[1].split("};", 1)[0]
    table = [int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]+)", body)]
    assert len(table) == 0x10000, len(table)
    return table


def runs(table):
    found = []
    for cp, lower in enumerate(table):
        if lower == cp:
            continue
        delta = (lower - cp) & 0xFFFF
        if found:
            first, last, run_delta, step = found[-1]
            if run_delta == delta and (cp - last == step if step else cp - last in (1, 2)):
                found[-1] = (first, cp, delta, cp - last)
                continue
        found.append((cp, cp, delta, 0))
    found = [(first, last, delta, step or 1) for first, last, delta, step in found]
    for cp, lower in enumerate(table):
        mapped = next(((cp + delta) & 0xFFFF for first, last, delta, step in found
                       if first <= cp <= last and (cp - first) % step == 0), cp)
        assert mapped == lower, hex(cp)
    return found


def render(table, version):
    lines = [
        f"/* Generated by gen_case_table.py from Samba {version} lowcase_table; do not edit.",
        " * case_runs: first, last, delta (mod 0x10000), step. */",
        "#ifndef TC_STORAGE_CASE_TABLE_H",
        "#define TC_STORAGE_CASE_TABLE_H",
        "static const unsigned short case_runs[][4] = {",
    ]
    lines += [f"    {{0x{first:04x}, 0x{last:04x}, 0x{delta:04x}, {step}}}," for first, last, delta, step in runs(table)]
    lines += ["};", "#endif"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("codepoints", type=pathlib.Path, help="Samba's lib/util/charset/codepoints.c")
    parser.add_argument("version", help="the Samba version it comes from")
    args = parser.parse_args()
    OUT.write_text(render(lowcase_table(args.codepoints.read_text()), args.version))


if __name__ == "__main__":
    main()
