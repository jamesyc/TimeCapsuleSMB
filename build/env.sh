#!/bin/sh

# Shared configuration for the reproducible NetBSD cross-build workflow.

SCRIPT_DIR=$(CDPATH= cd "$(dirname "$0")" && pwd)
REPO_ROOT=$(CDPATH= cd "$SCRIPT_DIR/.." && pwd)
ENV_FILE="${TC_ENV_FILE:-$SCRIPT_DIR/.env}"

PRESET_SDK_FAMILY="${SDK_FAMILY:-}"
PRESET_DEVICE_FAMILY="${DEVICE_FAMILY:-}"
PRESET_SAMBA_FAMILY="${SAMBA_FAMILY:-}"
PRESET_NETBSD4_ABI="${NETBSD4_ABI:-}"
PRESET_BUILD_ROOT="${BUILD_ROOT:-}"
PRESET_BUILD_SRC="${BUILD_SRC:-}"
PRESET_BUILD_OUT="${BUILD_OUT:-}"
PRESET_SRC="${SRC:-}"
PRESET_OUT="${OUT:-}"
PRESET_TC_PASSWORD_FILE="${TC_PASSWORD_FILE:-}"

if [ -f "$ENV_FILE" ]; then
    set -a
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    set +a
fi

NETBSD4LE_ROOT="${NETBSD4LE_ROOT:-/root/netbsd4}"
NETBSD4LE_SRC="${NETBSD4LE_SRC:-$NETBSD4LE_ROOT/usr/src}"
NETBSD4LE_OUT="${NETBSD4LE_OUT:-/root/tc-earmv4-netbsd4}"
NETBSD4LE_DOWNLOAD_LOG="${NETBSD4LE_DOWNLOAD_LOG:-$NETBSD4LE_OUT/download.log}"
NETBSD4LE_TOOLS_LOG="${NETBSD4LE_TOOLS_LOG:-$NETBSD4LE_OUT/bootstrap-tools.log}"
NETBSD4LE_DISTRIBUTION_LOG="${NETBSD4LE_DISTRIBUTION_LOG:-$NETBSD4LE_OUT/bootstrap-distribution.log}"

NETBSD4BE_ROOT="${NETBSD4BE_ROOT:-/root/netbsd4}"
NETBSD4BE_SRC="${NETBSD4BE_SRC:-$NETBSD4BE_ROOT/usr/src}"
NETBSD4BE_OUT="${NETBSD4BE_OUT:-/root/tc-armeb-netbsd4}"
NETBSD4BE_DOWNLOAD_LOG="${NETBSD4BE_DOWNLOAD_LOG:-$NETBSD4BE_OUT/download.log}"
NETBSD4BE_TOOLS_LOG="${NETBSD4BE_TOOLS_LOG:-$NETBSD4BE_OUT/bootstrap-tools.log}"
NETBSD4BE_DISTRIBUTION_LOG="${NETBSD4BE_DISTRIBUTION_LOG:-$NETBSD4BE_OUT/bootstrap-distribution.log}"

NETBSD7_ROOT="${NETBSD7_ROOT:-/root/netbsd7}"
NETBSD7_SRC="${NETBSD7_SRC:-$NETBSD7_ROOT/usr/src}"
NETBSD7_OUT="${NETBSD7_OUT:-/root/tc-earmv4-netbsd7}"
NETBSD7_DOWNLOAD_LOG="${NETBSD7_DOWNLOAD_LOG:-$NETBSD7_OUT/download.log}"
NETBSD7_TOOLS_LOG="${NETBSD7_TOOLS_LOG:-$NETBSD7_OUT/bootstrap-tools.log}"
NETBSD7_DISTRIBUTION_LOG="${NETBSD7_DISTRIBUTION_LOG:-$NETBSD7_OUT/bootstrap-distribution.log}"

HOST_CC="${HOST_CC:-/usr/pkg/gcc7/bin/gcc}"
HOST_CXX="${HOST_CXX:-/usr/pkg/gcc7/bin/g++}"
HOST_CFLAGS="${HOST_CFLAGS:--O -fcommon -fgnu89-inline}"
HOST_CXXFLAGS="${HOST_CXXFLAGS:--O -fcommon -fgnu89-inline}"
HOST_CPPFLAGS="${HOST_CPPFLAGS:--D__GNUC_GNU_INLINE__ -D__STDC_WANT_LIB_EXT1__=1}"
NO_PTHREADS="${NO_PTHREADS:-1}"

# Unset by default: any -j, including -j 1, turns off make(1) compatibility
# mode, which changes how target commands are run. Leaving this empty keeps
# build.sh invoked exactly as before.
SDK_JOBS="${SDK_JOBS:-}"

# Rc2 includes the upstream stream-parent and AFP_AfpInfo fixes. Our series
# still supplies NetBSD extent errno handling until upstream incorporates it.
SAMBA4X_VERSION="${SAMBA4X_VERSION:-4.25.0rc2}"
SAMBA4X_GIT_URL="${SAMBA4X_GIT_URL:-https://github.com/samba-team/samba.git}"
SAMBA4X_GIT_REF="${SAMBA4X_GIT_REF:-samba-${SAMBA4X_VERSION}}"
# Tags can be moved and mirrors can serve different bytes, so each download is
# pinned to what the shipped binaries were built from. Update the pin together
# with its version: the downloaders refuse a commit or archive that differs.
SAMBA4X_GIT_COMMIT="${SAMBA4X_GIT_COMMIT:-b5923e8d9563bcee569eb3f3ecc712a2a3761c1c}"
SAMBA4X_GMP_VERSION="${SAMBA4X_GMP_VERSION:-6.3.0}"
SAMBA4X_NETTLE_VERSION="${SAMBA4X_NETTLE_VERSION:-3.10.1}"
SAMBA4X_LIBTASN1_VERSION="${SAMBA4X_LIBTASN1_VERSION:-4.20.0}"
SAMBA4X_GNUTLS_VERSION="${SAMBA4X_GNUTLS_VERSION:-3.8.5}"
SAMBA4X_GMP_URL="${SAMBA4X_GMP_URL:-https://ftpmirror.gnu.org/gmp/gmp-${SAMBA4X_GMP_VERSION}.tar.xz}"
SAMBA4X_NETTLE_URL="${SAMBA4X_NETTLE_URL:-https://ftpmirror.gnu.org/nettle/nettle-${SAMBA4X_NETTLE_VERSION}.tar.gz}"
SAMBA4X_LIBTASN1_URL="${SAMBA4X_LIBTASN1_URL:-https://ftpmirror.gnu.org/libtasn1/libtasn1-${SAMBA4X_LIBTASN1_VERSION}.tar.gz}"
SAMBA4X_GNUTLS_URL="${SAMBA4X_GNUTLS_URL:-https://www.gnupg.org/ftp/gcrypt/gnutls/v3.8/gnutls-${SAMBA4X_GNUTLS_VERSION}.tar.xz}"
SAMBA4X_GMP_SHA256="${SAMBA4X_GMP_SHA256:-a3c2b80201b89e68616f4ad30bc66aee4927c3ce50e33929ca819d5c43538898}"
SAMBA4X_NETTLE_SHA256="${SAMBA4X_NETTLE_SHA256:-b0fcdd7fc0cdea6e80dcf1dd85ba794af0d5b4a57e26397eee3bc193272d9132}"
SAMBA4X_LIBTASN1_SHA256="${SAMBA4X_LIBTASN1_SHA256:-92e0e3bd4c02d4aeee76036b2ddd83f0c732ba4cda5cb71d583272b23587a76c}"
SAMBA4X_GNUTLS_SHA256="${SAMBA4X_GNUTLS_SHA256:-66269a2cfe0e1c2dabec87bdbbd8ab656f396edd9a40dd006978e003cfa52bfc}"

RSYNC_VERSION="${RSYNC_VERSION:-3.4.4}"
RSYNC_URL="${RSYNC_URL:-https://download.samba.org/pub/rsync/src/rsync-${RSYNC_VERSION}.tar.gz}"
RSYNC_ARCHIVE_NAME="${RSYNC_ARCHIVE_NAME:-rsync-${RSYNC_VERSION}.tar.gz}"
RSYNC_SHA256="${RSYNC_SHA256:-bd88cf82fa653da32314fb229136407c5c90f80d1758d8f4b091767877d8fa96}"
RSYNC_SRC_BASENAME="${RSYNC_SRC_BASENAME:-rsync-${RSYNC_VERSION}}"
RSYNC_SOURCE_WORK="${RSYNC_SOURCE_WORK:-/root/tc-rsync-source}"
RSYNC_COMMON_SRC_DIR="${RSYNC_COMMON_SRC_DIR:-$RSYNC_SOURCE_WORK/$RSYNC_SRC_BASENAME}"

SAMBA4X_NETBSD7_WORK="${SAMBA4X_NETBSD7_WORK:-/root/tc-samba4x-netbsd7}"
SAMBA4X_NETBSD7_SRC_DIR="${SAMBA4X_NETBSD7_SRC_DIR:-$SAMBA4X_NETBSD7_WORK/samba}"
SAMBA4X_NETBSD7_STAGE="${SAMBA4X_NETBSD7_STAGE:-/root/tc-netbsd7}"
SAMBA4X_NETBSD7_BUILD="${SAMBA4X_NETBSD7_BUILD:-$SAMBA4X_NETBSD7_WORK/build}"
SAMBA4X_NETBSD7_DOWNLOAD_LOG="${SAMBA4X_NETBSD7_DOWNLOAD_LOG:-$NETBSD7_OUT/downloadsamba4x.log}"
SAMBA4X_NETBSD7_LOG="${SAMBA4X_NETBSD7_LOG:-$NETBSD7_OUT/samba4x.log}"

RSYNC_NETBSD7_WORK="${RSYNC_NETBSD7_WORK:-/root/tc-rsync-netbsd7}"
RSYNC_NETBSD7_SRC_DIR="${RSYNC_NETBSD7_SRC_DIR:-$RSYNC_COMMON_SRC_DIR}"
RSYNC_NETBSD7_STAGE="${RSYNC_NETBSD7_STAGE:-/root/tc-netbsd7}"
RSYNC_NETBSD7_BUILD="${RSYNC_NETBSD7_BUILD:-$RSYNC_NETBSD7_WORK/build}"
RSYNC_NETBSD7_DOWNLOAD_LOG="${RSYNC_NETBSD7_DOWNLOAD_LOG:-$NETBSD7_OUT/downloadrsync.log}"
RSYNC_NETBSD7_LOG="${RSYNC_NETBSD7_LOG:-$NETBSD7_OUT/rsync.log}"

SAMBA4X_NETBSD4LE_WORK="${SAMBA4X_NETBSD4LE_WORK:-/root/tc-samba4x-netbsd4le}"
SAMBA4X_NETBSD4LE_SRC_DIR="${SAMBA4X_NETBSD4LE_SRC_DIR:-$SAMBA4X_NETBSD4LE_WORK/samba}"
SAMBA4X_NETBSD4LE_STAGE="${SAMBA4X_NETBSD4LE_STAGE:-/root/tc-netbsd4le}"
SAMBA4X_NETBSD4LE_BUILD="${SAMBA4X_NETBSD4LE_BUILD:-$SAMBA4X_NETBSD4LE_WORK/build}"
SAMBA4X_NETBSD4LE_DOWNLOAD_LOG="${SAMBA4X_NETBSD4LE_DOWNLOAD_LOG:-$NETBSD4LE_OUT/downloadsamba4xold.log}"
SAMBA4X_NETBSD4LE_LOG="${SAMBA4X_NETBSD4LE_LOG:-$NETBSD4LE_OUT/samba4xold.log}"

RSYNC_NETBSD4LE_WORK="${RSYNC_NETBSD4LE_WORK:-/root/tc-rsync-netbsd4le}"
RSYNC_NETBSD4LE_SRC_DIR="${RSYNC_NETBSD4LE_SRC_DIR:-$RSYNC_COMMON_SRC_DIR}"
RSYNC_NETBSD4LE_STAGE="${RSYNC_NETBSD4LE_STAGE:-/root/tc-netbsd4le}"
RSYNC_NETBSD4LE_BUILD="${RSYNC_NETBSD4LE_BUILD:-$RSYNC_NETBSD4LE_WORK/build}"
RSYNC_NETBSD4LE_DOWNLOAD_LOG="${RSYNC_NETBSD4LE_DOWNLOAD_LOG:-$NETBSD4LE_OUT/downloadrsyncold.log}"
RSYNC_NETBSD4LE_LOG="${RSYNC_NETBSD4LE_LOG:-$NETBSD4LE_OUT/rsyncold.log}"


SAMBA4X_NETBSD4BE_WORK="${SAMBA4X_NETBSD4BE_WORK:-/root/tc-samba4x-netbsd4be}"
SAMBA4X_NETBSD4BE_SRC_DIR="${SAMBA4X_NETBSD4BE_SRC_DIR:-$SAMBA4X_NETBSD4BE_WORK/samba}"
SAMBA4X_NETBSD4BE_STAGE="${SAMBA4X_NETBSD4BE_STAGE:-/root/tc-netbsd4be}"
SAMBA4X_NETBSD4BE_BUILD="${SAMBA4X_NETBSD4BE_BUILD:-$SAMBA4X_NETBSD4BE_WORK/build}"
SAMBA4X_NETBSD4BE_DOWNLOAD_LOG="${SAMBA4X_NETBSD4BE_DOWNLOAD_LOG:-$NETBSD4BE_OUT/downloadsamba4xold.log}"
SAMBA4X_NETBSD4BE_LOG="${SAMBA4X_NETBSD4BE_LOG:-$NETBSD4BE_OUT/samba4xold.log}"
SAMBA4X_NETBSD4_GC_SECTIONS="${SAMBA4X_NETBSD4_GC_SECTIONS:-1}"

RSYNC_NETBSD4BE_WORK="${RSYNC_NETBSD4BE_WORK:-/root/tc-rsync-netbsd4be}"
RSYNC_NETBSD4BE_SRC_DIR="${RSYNC_NETBSD4BE_SRC_DIR:-$RSYNC_COMMON_SRC_DIR}"
RSYNC_NETBSD4BE_STAGE="${RSYNC_NETBSD4BE_STAGE:-/root/tc-netbsd4be}"
RSYNC_NETBSD4BE_BUILD="${RSYNC_NETBSD4BE_BUILD:-$RSYNC_NETBSD4BE_WORK/build}"
RSYNC_NETBSD4BE_DOWNLOAD_LOG="${RSYNC_NETBSD4BE_DOWNLOAD_LOG:-$NETBSD4BE_OUT/downloadrsyncold.log}"
RSYNC_NETBSD4BE_LOG="${RSYNC_NETBSD4BE_LOG:-$NETBSD4BE_OUT/rsyncold.log}"

SAMBA4X_JOBS="${SAMBA4X_JOBS:-2}"
RSYNC_JOBS="${RSYNC_JOBS:-$SAMBA4X_JOBS}"
RSYNC_BIN_NAME="${RSYNC_BIN_NAME:-rsync}"

SERVICE_STAGE_NETBSD7="${SERVICE_STAGE_NETBSD7:-/root/tc-netbsd7}"
SERVICE_STAGE_NETBSD4LE="${SERVICE_STAGE_NETBSD4LE:-/root/tc-netbsd4le}"
SERVICE_STAGE_NETBSD4BE="${SERVICE_STAGE_NETBSD4BE:-/root/tc-netbsd4be}"

SAMBA4X_CROSS_EXEC_TMP_NETBSD7="${SAMBA4X_CROSS_EXEC_TMP_NETBSD7:-/tmp/tc-samba4x-probes-netbsd7}"
SAMBA4X_CROSS_EXEC_TMP_NETBSD4LE="${SAMBA4X_CROSS_EXEC_TMP_NETBSD4LE:-/mnt/Memory/tc-samba4x-probes-netbsd4le}"
SAMBA4X_CROSS_EXEC_TMP_NETBSD4BE="${SAMBA4X_CROSS_EXEC_TMP_NETBSD4BE:-/mnt/Memory/tc-samba4x-probes-netbsd4be}"

TC_NETBSD7_HOST="${TC_NETBSD7_HOST:-root@timecapsule.local}"
TC_NETBSD7_SSH_OPTS="${TC_NETBSD7_SSH_OPTS:--o HostKeyAlgorithms=+ssh-rsa -o PubkeyAcceptedAlgorithms=+ssh-rsa -o KexAlgorithms=+diffie-hellman-group14-sha1}"
TC_NETBSD7_SSH_PROXYCOMMAND="${TC_NETBSD7_SSH_PROXYCOMMAND:-}"
TC_NETBSD7_PASSWORD_FILE="${TC_NETBSD7_PASSWORD_FILE:-}"
TC_NETBSD7_PASSWORD="${TC_NETBSD7_PASSWORD:-}"

TC_NETBSD4LE_HOST="${TC_NETBSD4LE_HOST:-root@timecapsule.local}"
TC_NETBSD4LE_SSH_OPTS="${TC_NETBSD4LE_SSH_OPTS:--o HostKeyAlgorithms=+ssh-rsa -o PubkeyAcceptedAlgorithms=+ssh-rsa -o KexAlgorithms=+diffie-hellman-group14-sha1 -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null}"
TC_NETBSD4LE_SSH_PROXYCOMMAND="${TC_NETBSD4LE_SSH_PROXYCOMMAND:-}"
TC_NETBSD4LE_PASSWORD_FILE="${TC_NETBSD4LE_PASSWORD_FILE:-}"
TC_NETBSD4LE_PASSWORD="${TC_NETBSD4LE_PASSWORD:-}"

TC_NETBSD4BE_HOST="${TC_NETBSD4BE_HOST:-root@timecapsule.local}"
TC_NETBSD4BE_SSH_OPTS="${TC_NETBSD4BE_SSH_OPTS:--o HostKeyAlgorithms=+ssh-rsa -o PubkeyAcceptedAlgorithms=+ssh-rsa -o KexAlgorithms=+diffie-hellman-group14-sha1 -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null}"
TC_NETBSD4BE_SSH_PROXYCOMMAND="${TC_NETBSD4BE_SSH_PROXYCOMMAND:-}"
TC_NETBSD4BE_PASSWORD_FILE="${TC_NETBSD4BE_PASSWORD_FILE:-}"
TC_NETBSD4BE_PASSWORD="${TC_NETBSD4BE_PASSWORD:-}"

SDK_FAMILY="${PRESET_SDK_FAMILY:-${SDK_FAMILY:-netbsd7}}"
NETBSD4_ABI="${PRESET_NETBSD4_ABI:-${NETBSD4_ABI:-le}}"
case "$NETBSD4_ABI" in
    le|be)
        ;;
    *)
        echo "Unsupported NETBSD4_ABI: $NETBSD4_ABI" >&2
        echo "Expected one of: le, be" >&2
        return 1
        ;;
esac
case "$SDK_FAMILY" in
    netbsd4)
        BUILD_MACHINE="evbarm"
        if [ "$NETBSD4_ABI" = "be" ]; then
            BUILD_MACHINE_ARCH="armeb"
            BUILD_ROOT_DEFAULT="$NETBSD4BE_ROOT"
            BUILD_SRC_DEFAULT="$NETBSD4BE_SRC"
            BUILD_OUT_DEFAULT="$NETBSD4BE_OUT"
            SDK_DOWNLOAD_LOG_DEFAULT="$NETBSD4BE_DOWNLOAD_LOG"
            SDK_TOOLS_LOG_DEFAULT="$NETBSD4BE_TOOLS_LOG"
            SDK_DISTRIBUTION_LOG_DEFAULT="$NETBSD4BE_DISTRIBUTION_LOG"
            SERVICE_STAGE_DEFAULT="$SERVICE_STAGE_NETBSD4BE"
            CROSS_EXEC_REMOTE_DIR_DEFAULT="$SAMBA4X_CROSS_EXEC_TMP_NETBSD4BE"
            BUILD_EXPECT_ENDIAN="MSB"
            BUILD_EXPECT_TOOL_TRIPLE_GLOB="armeb*-netbsdelf"
            BUILD_EXPECT_HOST_ALIAS="armeb-unknown-netbsd4.0"
        else
            BUILD_MACHINE_ARCH="arm"
            BUILD_ROOT_DEFAULT="$NETBSD4LE_ROOT"
            BUILD_SRC_DEFAULT="$NETBSD4LE_SRC"
            BUILD_OUT_DEFAULT="$NETBSD4LE_OUT"
            SDK_DOWNLOAD_LOG_DEFAULT="$NETBSD4LE_DOWNLOAD_LOG"
            SDK_TOOLS_LOG_DEFAULT="$NETBSD4LE_TOOLS_LOG"
            SDK_DISTRIBUTION_LOG_DEFAULT="$NETBSD4LE_DISTRIBUTION_LOG"
            SERVICE_STAGE_DEFAULT="$SERVICE_STAGE_NETBSD4LE"
            CROSS_EXEC_REMOTE_DIR_DEFAULT="$SAMBA4X_CROSS_EXEC_TMP_NETBSD4LE"
            BUILD_EXPECT_ENDIAN="LSB"
            BUILD_EXPECT_TOOL_TRIPLE_GLOB="arm*-netbsdelf"
            BUILD_EXPECT_HOST_ALIAS="armv4-unknown-netbsd4.0"
        fi
        BUILD_EXPECT_OS_RELEASE="NetBSD 4.0"
        BUILD_EXPECT_EABI="EABI4"
        if [ "$NETBSD4_ABI" = "be" ]; then
            SDK_BOOTSTRAP_WRAPPER="./build/bootstrapoldbe.sh"
        else
            SDK_BOOTSTRAP_WRAPPER="./build/bootstrapoldle.sh"
        fi
        DEFAULT_DEVICE_FAMILY="old"
        ;;
    netbsd7)
        BUILD_MACHINE="evbarm"
        BUILD_MACHINE_ARCH="earmv4"
        BUILD_ROOT_DEFAULT="$NETBSD7_ROOT"
        BUILD_SRC_DEFAULT="$NETBSD7_SRC"
        BUILD_OUT_DEFAULT="$NETBSD7_OUT"
        SDK_DOWNLOAD_LOG_DEFAULT="$NETBSD7_DOWNLOAD_LOG"
        SDK_TOOLS_LOG_DEFAULT="$NETBSD7_TOOLS_LOG"
        SDK_DISTRIBUTION_LOG_DEFAULT="$NETBSD7_DISTRIBUTION_LOG"
        BUILD_EXPECT_OS_RELEASE="NetBSD 6.0"
        BUILD_EXPECT_HOST_ALIAS="armv4-unknown-netbsd7.2"
        BUILD_EXPECT_EABI="EABI4"
        BUILD_EXPECT_ENDIAN="LSB"
        BUILD_EXPECT_TOOL_TRIPLE_GLOB="arm*-netbsdelf"
        SDK_BOOTSTRAP_WRAPPER="./build/bootstrap.sh"
        SERVICE_STAGE_DEFAULT="$SERVICE_STAGE_NETBSD7"
        CROSS_EXEC_REMOTE_DIR_DEFAULT="$SAMBA4X_CROSS_EXEC_TMP_NETBSD7"
        DEFAULT_DEVICE_FAMILY="new"
        ;;
    *)
        echo "Unsupported SDK_FAMILY: $SDK_FAMILY" >&2
        echo "Expected one of: netbsd4, netbsd7" >&2
        return 1
        ;;
esac

BUILD_ROOT="${PRESET_BUILD_ROOT:-${BUILD_ROOT:-$BUILD_ROOT_DEFAULT}}"
BUILD_SRC="${PRESET_BUILD_SRC:-${BUILD_SRC:-${PRESET_SRC:-$BUILD_SRC_DEFAULT}}}"
BUILD_OUT="${PRESET_BUILD_OUT:-${BUILD_OUT:-${PRESET_OUT:-$BUILD_OUT_DEFAULT}}}"
SRC="$BUILD_SRC"
OUT="$BUILD_OUT"
OBJ="$OUT/obj"
TOOLS="$OUT/tools"
STAMPS="$OUT/stamps"
TOOLS_STAMP="$STAMPS/tools.ok"
DIST_STAMP="$STAMPS/distribution.ok"

DOWNLOAD_LOG="${DOWNLOAD_LOG:-$SDK_DOWNLOAD_LOG_DEFAULT}"
TOOLS_LOG="${TOOLS_LOG:-$SDK_TOOLS_LOG_DEFAULT}"
DIST_LOG="${DIST_LOG:-$SDK_DISTRIBUTION_LOG_DEFAULT}"
HELLO_LOG="${HELLO_LOG:-$OUT/hello.log}"
PROBE_DIR="${PROBE_DIR:-$OUT/probe}"
PROBE_SRC="${PROBE_SRC:-$PROBE_DIR/hello.c}"
PROBE_BIN="${PROBE_BIN:-$PROBE_DIR/hello}"
SERVICE_STAGE="${SERVICE_STAGE:-$SERVICE_STAGE_DEFAULT}"
SERVICE_LOG="${SERVICE_LOG:-$OUT/service.log}"
CROSS_EXEC_REMOTE_DIR="${CROSS_EXEC_REMOTE_DIR:-$CROSS_EXEC_REMOTE_DIR_DEFAULT}"

DEVICE_FAMILY="${PRESET_DEVICE_FAMILY:-${DEVICE_FAMILY:-$DEFAULT_DEVICE_FAMILY}}"
case "$SDK_FAMILY:$NETBSD4_ABI" in
    netbsd7:*)
        TC_HOST="$TC_NETBSD7_HOST"
        TC_SSH_OPTS="$TC_NETBSD7_SSH_OPTS"
        TC_SSH_PROXYCOMMAND="$TC_NETBSD7_SSH_PROXYCOMMAND"
        TC_PASSWORD_FILE_DEFAULT="$TC_NETBSD7_PASSWORD_FILE"
        TC_PASSWORD_DEFAULT="$TC_NETBSD7_PASSWORD"
        ;;
    netbsd4:le)
        TC_HOST="$TC_NETBSD4LE_HOST"
        TC_SSH_OPTS="$TC_NETBSD4LE_SSH_OPTS"
        TC_SSH_PROXYCOMMAND="$TC_NETBSD4LE_SSH_PROXYCOMMAND"
        TC_PASSWORD_FILE_DEFAULT="$TC_NETBSD4LE_PASSWORD_FILE"
        TC_PASSWORD_DEFAULT="$TC_NETBSD4LE_PASSWORD"
        ;;
    netbsd4:be)
        TC_HOST="$TC_NETBSD4BE_HOST"
        TC_SSH_OPTS="$TC_NETBSD4BE_SSH_OPTS"
        TC_SSH_PROXYCOMMAND="$TC_NETBSD4BE_SSH_PROXYCOMMAND"
        TC_PASSWORD_FILE_DEFAULT="$TC_NETBSD4BE_PASSWORD_FILE"
        TC_PASSWORD_DEFAULT="$TC_NETBSD4BE_PASSWORD"
        ;;
    *)
        echo "Unsupported SDK_FAMILY/NETBSD4_ABI combination for device connection: $SDK_FAMILY / $NETBSD4_ABI" >&2
        return 1
        ;;
esac

TC_PASSWORD_FILE="${PRESET_TC_PASSWORD_FILE:-${TC_PASSWORD_FILE:-$TC_PASSWORD_FILE_DEFAULT}}"
TC_PASSWORD="${TC_PASSWORD:-$TC_PASSWORD_DEFAULT}"

SAMBA_FAMILY="${PRESET_SAMBA_FAMILY:-${SAMBA_FAMILY:-}}"
WORK=
SRC_DIR=
STAGE=
HOST_ALIAS="$BUILD_EXPECT_HOST_ALIAS"
SAMBA_DOWNLOAD_WRAPPER=

case "$SAMBA_FAMILY:$SDK_FAMILY" in
    samba4x:netbsd7)
        WORK="$SAMBA4X_NETBSD7_WORK"
        SRC_DIR="$SAMBA4X_NETBSD7_SRC_DIR"
        STAGE="$SAMBA4X_NETBSD7_STAGE"
        HOST_ALIAS="${SAMBA4X_HOST_ALIAS:-$BUILD_EXPECT_HOST_ALIAS}"
        SAMBA_DOWNLOAD_WRAPPER="./build/downloadsamba4x.sh"
        ;;
    samba4x:netbsd4)
        HOST_ALIAS="${SAMBA4X_HOST_ALIAS:-$BUILD_EXPECT_HOST_ALIAS}"
        if [ "$NETBSD4_ABI" = "be" ]; then
            WORK="$SAMBA4X_NETBSD4BE_WORK"
            SRC_DIR="$SAMBA4X_NETBSD4BE_SRC_DIR"
            STAGE="$SAMBA4X_NETBSD4BE_STAGE"
            SAMBA_DOWNLOAD_WRAPPER="./build/downloadsamba4xoldbe.sh"
        else
            WORK="$SAMBA4X_NETBSD4LE_WORK"
            SRC_DIR="$SAMBA4X_NETBSD4LE_SRC_DIR"
            STAGE="$SAMBA4X_NETBSD4LE_STAGE"
            SAMBA_DOWNLOAD_WRAPPER="./build/downloadsamba4xoldle.sh"
        fi
        ;;
    :*)
        ;;
    *)
        echo "Unsupported SAMBA_FAMILY/SDK_FAMILY combination: $SAMBA_FAMILY / $SDK_FAMILY" >&2
        return 1
        ;;
esac

if [ "$SDK_FAMILY" = "netbsd7" ]; then
    SAMBA4X_WORK="${SAMBA4X_WORK:-$SAMBA4X_NETBSD7_WORK}"
    SAMBA4X_SRC_DIR="${SAMBA4X_SRC_DIR:-$SAMBA4X_NETBSD7_SRC_DIR}"
    SAMBA4X_STAGE="${SAMBA4X_STAGE:-$SAMBA4X_NETBSD7_STAGE}"
    SAMBA4X_BUILD="${SAMBA4X_BUILD:-$SAMBA4X_NETBSD7_BUILD}"
    SAMBA4X_DEPS="${SAMBA4X_DEPS:-$SAMBA4X_BUILD/deps}"
    SAMBA4X_DOWNLOAD_LOG="${SAMBA4X_DOWNLOAD_LOG:-$SAMBA4X_NETBSD7_DOWNLOAD_LOG}"
    SAMBA4X_LOG="${SAMBA4X_LOG:-$SAMBA4X_NETBSD7_LOG}"
    SAMBA4X_CROSS_EXEC_REMOTE_DIR="${SAMBA4X_CROSS_EXEC_REMOTE_DIR:-$SAMBA4X_CROSS_EXEC_TMP_NETBSD7}"
    RSYNC_WORK="${RSYNC_WORK:-$RSYNC_NETBSD7_WORK}"
    RSYNC_SRC_DIR="${RSYNC_SRC_DIR:-$RSYNC_NETBSD7_SRC_DIR}"
    RSYNC_STAGE="${RSYNC_STAGE:-$RSYNC_NETBSD7_STAGE}"
    RSYNC_BUILD="${RSYNC_BUILD:-$RSYNC_NETBSD7_BUILD}"
    RSYNC_DOWNLOAD_LOG="${RSYNC_DOWNLOAD_LOG:-$RSYNC_NETBSD7_DOWNLOAD_LOG}"
    RSYNC_LOG="${RSYNC_LOG:-$RSYNC_NETBSD7_LOG}"
else
    if [ "$NETBSD4_ABI" = "be" ]; then
        SAMBA4X_WORK="${SAMBA4X_WORK:-$SAMBA4X_NETBSD4BE_WORK}"
        SAMBA4X_SRC_DIR="${SAMBA4X_SRC_DIR:-$SAMBA4X_NETBSD4BE_SRC_DIR}"
        SAMBA4X_STAGE="${SAMBA4X_STAGE:-$SAMBA4X_NETBSD4BE_STAGE}"
        SAMBA4X_BUILD="${SAMBA4X_BUILD:-$SAMBA4X_NETBSD4BE_BUILD}"
        SAMBA4X_DEPS="${SAMBA4X_DEPS:-$SAMBA4X_BUILD/deps}"
        SAMBA4X_DOWNLOAD_LOG="${SAMBA4X_DOWNLOAD_LOG:-$SAMBA4X_NETBSD4BE_DOWNLOAD_LOG}"
        SAMBA4X_LOG="${SAMBA4X_LOG:-$SAMBA4X_NETBSD4BE_LOG}"
        SAMBA4X_CROSS_EXEC_REMOTE_DIR="${SAMBA4X_CROSS_EXEC_REMOTE_DIR:-$SAMBA4X_CROSS_EXEC_TMP_NETBSD4BE}"
        RSYNC_WORK="${RSYNC_WORK:-$RSYNC_NETBSD4BE_WORK}"
        RSYNC_SRC_DIR="${RSYNC_SRC_DIR:-$RSYNC_NETBSD4BE_SRC_DIR}"
        RSYNC_STAGE="${RSYNC_STAGE:-$RSYNC_NETBSD4BE_STAGE}"
